#[derive(Clone)]
enum Offer {
    Ext(ext_impl::Offer),
    Wlr(wlr_impl::Offer),
}

enum Source {
    Ext(ext_impl::Source),
    Wlr(wlr_impl::Source),
}

enum Device {
    Ext(ext_impl::Device),
    Wlr(wlr_impl::Device),
}

enum Manager {
    Ext(ext_impl::Manager),
    Wlr(wlr_impl::Manager),
}

impl Offer {
    fn mimes(&self) -> Vec<String> {
        let data = match self {
            Self::Ext(o) => o.data::<OfferData>(),
            Self::Wlr(o) => o.data::<OfferData>(),
        };
        data.and_then(|d| d.mimes.lock().ok().map(|m| m.clone()))
            .unwrap_or_default()
    }
    fn receive(&self, mime: &str, fd: BorrowedFd<'_>) {
        match self {
            Self::Ext(o) => o.receive(mime.to_owned(), fd),
            Self::Wlr(o) => o.receive(mime.to_owned(), fd),
        }
    }
    fn destroy(&self) {
        match self {
            Self::Ext(o) => o.destroy(),
            Self::Wlr(o) => o.destroy(),
        }
    }
}

impl Source {
    fn offer(&self, mime: &str) {
        match self {
            Self::Ext(s) => s.offer(mime.to_owned()),
            Self::Wlr(s) => s.offer(mime.to_owned()),
        }
    }
    fn destroy(&self) {
        match self {
            Self::Ext(s) => s.destroy(),
            Self::Wlr(s) => s.destroy(),
        }
    }
}

impl Device {
    fn set_selection(&self, source: Option<&Source>) {
        match (self, source) {
            (Self::Ext(d), Some(Source::Ext(s))) => d.set_selection(Some(s)),
            (Self::Wlr(d), Some(Source::Wlr(s))) => d.set_selection(Some(s)),
            (Self::Ext(d), None) => d.set_selection(None),
            (Self::Wlr(d), None) => d.set_selection(None),
            _ => {}
        }
    }
    fn destroy(&self) {
        match self {
            Self::Ext(d) => d.destroy(),
            Self::Wlr(d) => d.destroy(),
        }
    }
}

impl Manager {
    fn get_data_device(&self, seat: &wl_seat::WlSeat, qh: &QueueHandle<State>) -> Device {
        match self {
            Self::Ext(m) => Device::Ext(m.get_data_device(seat, qh, ())),
            Self::Wlr(m) => Device::Wlr(m.get_data_device(seat, qh, ())),
        }
    }
    fn create_data_source(&self, qh: &QueueHandle<State>, data: SourceData) -> Source {
        match self {
            Self::Ext(m) => Source::Ext(m.create_data_source(qh, data)),
            Self::Wlr(m) => Source::Wlr(m.create_data_source(qh, data)),
        }
    }
}

#[derive(Default)]
struct State {
    selection: Option<Offer>,
    selection_dirty: bool,
    revision: Option<Arc<AtomicU64>>,
    finished: bool,
    own: Option<OwnSource>,
}

impl State {
    fn on_selection(&mut self, offer: Option<Offer>) {
        if let Some(revision) = &self.revision {
            let mimes = offer.as_ref().map(Offer::mimes).unwrap_or_default();
            observe_selection(
                revision,
                &mimes,
                self.own.as_ref().map(|own| own.marker.as_str()),
            );
        }
        if let Some(old) = std::mem::replace(&mut self.selection, offer) {
            old.destroy();
        }
        self.selection_dirty = true;
    }

    fn on_source_cancelled(&mut self, id: u64) {
        if self.own.as_ref().is_some_and(|o| o.id == id)
            && let Some(own) = self.own.take()
        {
            own.source.destroy();
        }
    }
}

/// Observe metadata on the Wayland thread before any potentially slow payload reads.
fn observe_selection(revision: &AtomicU64, mimes: &[String], own_marker: Option<&str>) {
    let own_write = own_marker.is_some_and(|marker| mimes.iter().any(|mime| mime == marker));
    if !own_write {
        revision.fetch_add(1, Ordering::Relaxed);
    }
}

impl Dispatch<wl_registry::WlRegistry, GlobalListContents> for State {
    fn event(
        _: &mut Self,
        _: &wl_registry::WlRegistry,
        _: wl_registry::Event,
        _: &GlobalListContents,
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
    }
}

impl Dispatch<wl_seat::WlSeat, ()> for State {
    fn event(
        _: &mut Self,
        _: &wl_seat::WlSeat,
        _: wl_seat::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
    }
}

fn serve_source(payload: &Arc<Payload>, mime: &str, fd: OwnedFd) {
    let Some(bytes) = payload.items.get(mime).cloned() else {
        return;
    };
    // Writing may block on a slow reader: use a short-lived thread per request.
    let _ = std::thread::Builder::new()
        .name("kebloop-clipboard-send".into())
        .spawn(move || {
            let _ = write_all_timeout(&fd, &bytes, Duration::from_secs(10));
        });
}

macro_rules! impl_protocol {
    ($variant:ident, $mgr:ident, $dev_mod:ident, $dev:ident, $off_mod:ident, $off:ident, $src_mod:ident, $src:ident) => {
        pub type Manager = $mgr;
        pub type Device = $dev;
        pub type Offer = $off;
        pub type Source = $src;

        impl Dispatch<$mgr, ()> for State {
            fn event(
                _: &mut Self,
                _: &$mgr,
                _: <$mgr as Proxy>::Event,
                _: &(),
                _: &Connection,
                _: &QueueHandle<Self>,
            ) {
            }
        }

        impl Dispatch<$dev, ()> for State {
            fn event(
                state: &mut Self,
                _: &$dev,
                event: $dev_mod::Event,
                _: &(),
                _: &Connection,
                _: &QueueHandle<Self>,
            ) {
                match event {
                    $dev_mod::Event::DataOffer { .. } => {}
                    $dev_mod::Event::Selection { id } => {
                        state.on_selection(id.map(super::Offer::$variant));
                    }
                    $dev_mod::Event::PrimarySelection { id: Some(offer) } => offer.destroy(),
                    $dev_mod::Event::PrimarySelection { id: None } => {}
                    $dev_mod::Event::Finished => state.finished = true,
                    _ => {}
                }
            }

            wayland_client::event_created_child!(State, $dev, [
                $dev_mod::EVT_DATA_OFFER_OPCODE => ($off, OfferData::default()),
            ]);
        }

        impl Dispatch<$off, OfferData> for State {
            fn event(
                _: &mut Self,
                _: &$off,
                event: $off_mod::Event,
                data: &OfferData,
                _: &Connection,
                _: &QueueHandle<Self>,
            ) {
                if let $off_mod::Event::Offer { mime_type } = event {
                    if let Ok(mut mimes) = data.mimes.lock() {
                        mimes.push(mime_type);
                    }
                }
            }
        }

        impl Dispatch<$src, SourceData> for State {
            fn event(
                state: &mut Self,
                source: &$src,
                event: $src_mod::Event,
                data: &SourceData,
                _: &Connection,
                _: &QueueHandle<Self>,
            ) {
                match event {
                    $src_mod::Event::Send { mime_type, fd } => {
                        serve_source(&data.payload, &mime_type, fd);
                    }
                    $src_mod::Event::Cancelled => {
                        // Sources replaced by our own newer source are already destroyed.
                        if state.own.as_ref().is_some_and(|o| o.id == data.id) {
                            state.on_source_cancelled(data.id);
                        } else {
                            source.destroy();
                        }
                    }
                    _ => {}
                }
            }
        }
    };
}

