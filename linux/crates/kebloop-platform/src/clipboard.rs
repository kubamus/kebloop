/// Completion callback of a clipboard command; runs on the clipboard thread.
pub type Reply = Box<dyn FnOnce(Result<(), ClipboardError>) + Send>;

enum Command {
    Set {
        data: BTreeMap<String, Vec<u8>>,
        transient: bool,
        reply: Reply,
    },
    Clear {
        reply: Reply,
    },
    Stop,
}

static SOURCE_COUNTER: AtomicU64 = AtomicU64::new(1);

fn with_text_aliases(mut data: BTreeMap<String, Vec<u8>>) -> BTreeMap<String, Vec<u8>> {
    let existing = data
        .iter()
        .filter_map(|(k, v)| text_rank(k).map(|rank| (rank, v)))
        .min_by_key(|(rank, _)| *rank)
        .map(|(_, v)| v.clone());
    if let Some(bytes) = existing {
        for alias in [TEXT_KEY, "text/plain", "UTF8_STRING"] {
            if !data.keys().any(|k| loose(k) == loose(alias)) {
                data.insert(alias.to_owned(), bytes.clone());
            }
        }
    }
    data
}

struct Runtime {
    conn: Connection,
    queue: EventQueue<State>,
    state: State,
    manager: Manager,
    device: Device,
}

impl Runtime {
    fn set(&mut self, data: BTreeMap<String, Vec<u8>>, transient: bool) {
        let id = SOURCE_COUNTER.fetch_add(1, Ordering::Relaxed);
        let marker = format!("application/x-kebloop-source-{}-{id}", std::process::id());
        let items: BTreeMap<String, Arc<Vec<u8>>> = with_text_aliases(data)
            .into_iter()
            .map(|(k, v)| (k, Arc::new(v)))
            .collect();
        let payload = Arc::new(Payload { items });
        let source = self.manager.create_data_source(
            &self.queue.handle(),
            SourceData {
                id,
                payload: payload.clone(),
            },
        );
        for mime in payload.items.keys() {
            source.offer(mime);
        }
        source.offer(&marker);
        if transient {
            source.offer(TRANSIENT_MIME);
        }
        self.device.set_selection(Some(&source));
        if let Some(old) = self.state.own.replace(OwnSource {
            id,
            source,
            marker,
            payload,
            transient,
        }) {
            old.source.destroy();
        }
    }

    fn clear(&mut self) {
        self.device.set_selection(None);
        if let Some(old) = self.state.own.take() {
            old.source.destroy();
        }
    }
}

fn pick_manager(
    globals: &GlobalList,
    qh: &QueueHandle<State>,
    force_wlr: bool,
) -> Result<Manager, ClipboardError> {
    let has_wlr = globals.contents().with_list(|l| {
        l.iter()
            .any(|g| g.interface == "zwlr_data_control_manager_v1")
    });
    let backend = if force_wlr && has_wlr {
        ClipboardBackend::WlrDataControl
    } else {
        backend_from_globals(globals)
    };
    match backend {
        ClipboardBackend::ExtDataControl => globals
            .bind::<ext_impl::Manager, _, _>(qh, 1..=1, ())
            .map(Manager::Ext)
            .map_err(|e| ClipboardError::Wayland(e.to_string())),
        ClipboardBackend::WlrDataControl => globals
            .bind::<wlr_impl::Manager, _, _>(qh, 1..=2, ())
            .map(Manager::Wlr)
            .map_err(|e| ClipboardError::Wayland(e.to_string())),
        ClipboardBackend::Gnome => Err(ClipboardError::Unavailable(
            "GNOME is not a Wayland data-control protocol".into(),
        )),
        ClipboardBackend::X11 => Err(ClipboardError::Unavailable(
            "X11 is not a Wayland protocol".into(),
        )),
        ClipboardBackend::Unavailable(reason) => Err(ClipboardError::Unavailable(reason)),
    }
}

fn setup(
    qh_out: &mut Option<Runtime>,
    force_wlr: bool,
) -> Result<ClipboardBackend, ClipboardError> {
    let conn = Connection::connect_to_env()
        .map_err(|e| ClipboardError::Unavailable(format!("cannot connect to Wayland: {e}")))?;
    let (globals, mut queue) =
        registry_queue_init::<State>(&conn).map_err(|e| ClipboardError::Wayland(e.to_string()))?;
    let qh = queue.handle();
    let manager = pick_manager(&globals, &qh, force_wlr)?;
    let backend = match manager {
        Manager::Ext(_) => ClipboardBackend::ExtDataControl,
        Manager::Wlr(_) => ClipboardBackend::WlrDataControl,
    };
    let seat = globals
        .bind::<wl_seat::WlSeat, _, _>(&qh, 1..=1, ())
        .map_err(|e| ClipboardError::Unavailable(format!("no wl_seat: {e}")))?;
    let device = manager.get_data_device(&seat, &qh);
    let mut state = State::default();
    // The compositor announces the current selection right after the device is
    // created. It is intentionally discarded: only later changes are ingested.
    queue
        .roundtrip(&mut state)
        .map_err(|e| ClipboardError::Wayland(e.to_string()))?;
    if let Some(initial) = state.selection.take() {
        initial.destroy();
    }
    state.selection_dirty = false;
    *qh_out = Some(Runtime {
        conn,
        queue,
        state,
        manager,
        device,
    });
    Ok(backend)
}

fn run_loop(
    mut rt: Runtime,
    cfg: &ClipboardConfig,
    commands: &mpsc::Receiver<Command>,
    wake: &UnixStream,
    jobs: &mpsc::Sender<Job>,
) -> Result<(), ClipboardError> {
    let wayland_err = |e: &dyn std::fmt::Display| ClipboardError::Wayland(e.to_string());
    rt.state.revision = Some(cfg.revision.clone());
    loop {
        while let Ok(cmd) = commands.try_recv() {
            match cmd {
                Command::Stop => {
                    rt.device.destroy();
                    let _ = rt.conn.flush();
                    return Ok(());
                }
                Command::Set {
                    data,
                    transient,
                    reply,
                } => {
                    rt.set(data, transient);
                    reply(rt.conn.flush().map_err(|e| wayland_err(&e)));
                }
                Command::Clear { reply } => {
                    rt.clear();
                    reply(rt.conn.flush().map_err(|e| wayland_err(&e)));
                }
            }
        }

        rt.queue
            .dispatch_pending(&mut rt.state)
            .map_err(|e| wayland_err(&e))?;
        if rt.state.finished {
            return Err(ClipboardError::Wayland(
                "data device was finished by the compositor".into(),
            ));
        }
        if rt.state.selection_dirty {
            rt.state.selection_dirty = false;
            if let Some(offer) = rt.state.selection.clone() {
                let job = prepare_job(&rt.conn, &offer, cfg, rt.state.own.as_ref());
                if jobs.send(job).is_err() {
                    return Ok(());
                }
            }
        }
        rt.conn.flush().map_err(|e| wayland_err(&e))?;

        let Some(guard) = rt.queue.prepare_read() else {
            continue;
        };
        let ready = {
            let conn_fd = guard.connection_fd();
            let mut fds = [
                PollFd::new(&conn_fd, PollFlags::IN),
                PollFd::new(wake, PollFlags::IN),
            ];
            match poll(&mut fds, None) {
                Ok(_) => (
                    fds[0]
                        .revents()
                        .intersects(PollFlags::IN | PollFlags::ERR | PollFlags::HUP),
                    fds[1].revents().contains(PollFlags::IN),
                ),
                Err(Errno::INTR) => (false, false),
                Err(e) => return Err(wayland_err(&e)),
            }
        };
        if ready.0 {
            match guard.read() {
                Ok(_) => {}
                Err(wayland_client::backend::WaylandError::Io(e))
                    if e.kind() == io::ErrorKind::WouldBlock => {}
                Err(e) => return Err(wayland_err(&e)),
            }
        } else {
            drop(guard);
        }
        if ready.1 {
            let mut sink = [0u8; 64];
            let mut reader = wake;
            while io::Read::read(&mut reader, &mut sink).is_ok_and(|n| n > 0) {}
        }
    }
}

/// Handle to the clipboard thread. Dropping it stops the thread.
pub struct ClipboardWatcher {
    backend: ClipboardBackend,
    commands: mpsc::Sender<Command>,
    wake: UnixStream,
    running: Arc<AtomicBool>,
    last_error: Arc<Mutex<Option<String>>>,
    recording: Arc<AtomicBool>,
}

impl ClipboardWatcher {
    /// Starts the clipboard thread. Returns `Err(Unavailable)` when the
    /// compositor has no data-control protocol or the session is X11.
    pub fn start(
        config: ClipboardConfig,
    ) -> Result<(Self, async_channel::Receiver<ClipboardEvent>), ClipboardError> {
        let backend = detect_backend();
        if backend == ClipboardBackend::Gnome {
            return gnome::start(config);
        }
        if backend == ClipboardBackend::X11 {
            return x11::start(config);
        }
        if let ClipboardBackend::Unavailable(reason) = backend {
            return Err(ClipboardError::Unavailable(reason));
        }
        let (events_tx, events_rx) = async_channel::bounded(64);
        let (cmd_tx, cmd_rx) = mpsc::channel();
        let (wake_tx, wake_rx) =
            UnixStream::pair().map_err(|e| ClipboardError::Wayland(e.to_string()))?;
        wake_tx
            .set_nonblocking(true)
            .map_err(|e| ClipboardError::Wayland(e.to_string()))?;
        wake_rx
            .set_nonblocking(true)
            .map_err(|e| ClipboardError::Wayland(e.to_string()))?;
        let (ready_tx, ready_rx) = mpsc::channel::<Result<ClipboardBackend, ClipboardError>>();
        let running = Arc::new(AtomicBool::new(true));
        let last_error = Arc::new(Mutex::new(None));

        let (jobs_tx, jobs_rx) = mpsc::channel::<Job>();
        let reader_config = config.clone();
        std::thread::Builder::new()
            .name("kebloop-clipboard-read".into())
            .spawn(move || {
                // Collects the data of each selection in order, off the Wayland thread.
                while let Ok(job) = jobs_rx.recv() {
                    let event = finish_job(job, &reader_config);
                    if events_tx.send_blocking(event).is_err() {
                        break;
                    }
                }
            })
            .map_err(|e| ClipboardError::Wayland(e.to_string()))?;

        let thread_running = running.clone();
        let thread_error = last_error.clone();
        let recording = config.recording.clone();
        std::thread::Builder::new()
            .name("kebloop-clipboard".into())
            .spawn(move || {
                let mut runtime = None;
                match setup(&mut runtime, config.force_wlr) {
                    Ok(backend) => {
                        let _ = ready_tx.send(Ok(backend));
                    }
                    Err(e) => {
                        let _ = ready_tx.send(Err(e));
                        thread_running.store(false, Ordering::Relaxed);
                        return;
                    }
                }
                if let Some(rt) = runtime
                    && let Err(e) = run_loop(rt, &config, &cmd_rx, &wake_rx, &jobs_tx)
                    && let Ok(mut slot) = thread_error.lock()
                {
                    *slot = Some(e.to_string());
                }
                thread_running.store(false, Ordering::Relaxed);
            })
            .map_err(|e| ClipboardError::Wayland(e.to_string()))?;

        let backend = match ready_rx.recv_timeout(Duration::from_secs(10)) {
            Ok(Ok(backend)) => backend,
            Ok(Err(e)) => return Err(e),
            Err(_) => return Err(ClipboardError::Timeout),
        };
        Ok((
            Self {
                backend,
                commands: cmd_tx,
                wake: wake_tx,
                running,
                last_error,
                recording,
            },
            events_rx,
        ))
    }

    pub fn backend(&self) -> &ClipboardBackend {
        &self.backend
    }

    /// Whether the thread is still alive.
    pub fn is_running(&self) -> bool {
        self.running.load(Ordering::Relaxed)
    }

    /// Why the thread stopped, if it died with an error.
    pub fn last_error(&self) -> Option<String> {
        self.last_error.lock().ok().and_then(|e| e.clone())
    }

    fn wake(&self) {
        let _ = io::Write::write(&mut &self.wake, &[1]);
    }

    /// Queues a command for the clipboard thread without waiting for it. `Err` means the thread
    /// is not running (the command was not queued); otherwise `done` runs on the clipboard thread
    /// with the outcome, or is dropped uncalled if the thread dies first.
    fn submit(
        &self,
        make: impl FnOnce(Reply) -> Command,
        done: impl FnOnce(Result<(), ClipboardError>) + Send + 'static,
    ) -> Result<(), ClipboardError> {
        if !self.is_running() {
            return Err(ClipboardError::NotRunning);
        }
        self.commands
            .send(make(Box::new(done)))
            .map_err(|_| ClipboardError::NotRunning)?;
        self.wake();
        Ok(())
    }

    /// Blocks up to five seconds for a command (tests and tools; never call from a UI thread).
    fn request(&self, make: impl FnOnce(Reply) -> Command) -> Result<(), ClipboardError> {
        let (tx, rx) = mpsc::channel();
        self.submit(make, move |result| {
            let _ = tx.send(result);
        })?;
        rx.recv_timeout(Duration::from_secs(5))
            .map_err(|e| match e {
                mpsc::RecvTimeoutError::Timeout => ClipboardError::Timeout,
                mpsc::RecvTimeoutError::Disconnected => ClipboardError::NotRunning,
            })?
    }

    /// Switches content reading on or off (see [`ClipboardConfig::recording`]).
    pub fn set_recording(&self, recording: bool) {
        self.recording.store(recording, Ordering::Relaxed);
    }

    /// Becomes the clipboard owner and serves `data` (mime → bytes) until
    /// another client replaces the selection, without waiting for the clipboard thread: the
    /// outcome is reported to `done` (called on the clipboard thread; hop to your own thread
    /// there). `Err` means the thread is not running and nothing was queued. Text variants missing
    /// from `data` (`text/plain`, `text/plain;charset=utf-8`, `UTF8_STRING`) are added as
    /// aliases. With `transient` the extra mime [`TRANSIENT_MIME`] is offered so clipboard
    /// managers (including Kebloop's own store) can skip the entry. The watcher reports the write
    /// as an event with `own_write = true`.
    pub fn set_clipboard_async(
        &self,
        data: BTreeMap<String, Vec<u8>>,
        transient: bool,
        done: impl FnOnce(Result<(), ClipboardError>) + Send + 'static,
    ) -> Result<(), ClipboardError> {
        self.submit(
            |reply| Command::Set {
                data,
                transient,
                reply,
            },
            done,
        )
    }

    /// Like [`ClipboardWatcher::set_clipboard_async`] but waits (up to five seconds) for the
    /// result. For tests and tools, not for UI threads.
    pub fn set_clipboard(
        &self,
        data: BTreeMap<String, Vec<u8>>,
        transient: bool,
    ) -> Result<(), ClipboardError> {
        self.request(|reply| Command::Set {
            data,
            transient,
            reply,
        })
    }

    /// Clears the selection (waits up to five seconds for the result).
    pub fn clear_clipboard(&self) -> Result<(), ClipboardError> {
        self.request(|reply| Command::Clear { reply })
    }
}

impl Drop for ClipboardWatcher {
    fn drop(&mut self) {
        let _ = self.commands.send(Command::Stop);
        self.wake();
    }
}

