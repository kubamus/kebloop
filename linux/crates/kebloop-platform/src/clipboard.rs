//! Wayland clipboard watcher and setter that works without window focus.
//!
//! Uses `ext-data-control-v1` when the compositor advertises it and falls back
//! to `zwlr_data_control_manager_v1`. A dedicated thread owns the Wayland
//! connection; clipboard changes arrive as [`ClipboardEvent`]s on an
//! `async-channel` and [`ClipboardWatcher::set_clipboard`] serves data as a
//! data-control source until it is replaced.
//!
//! * The selection that exists when the watcher starts is **not** ingested.
//! * Selections carrying sensitive marker types (`x-kde-passwordManagerHint`,
//!   `application/x-nspasteboard-concealed-type`, anything containing
//!   `concealed`, `transient`, `autogenerated` or `passwordmanagerhint`) are
//!   reported with `sensitive = true`; only the marker values are read and the
//!   data of every other type is never requested.
//! * While recording is off or paused (see [`ClipboardConfig::recording`]) no
//!   content is read at all, only the list of offered mime types.
//! * Every pipe read is size-capped and non-blocking with a timeout and runs on
//!   a helper thread, so a misbehaving source can neither hang nor delay the
//!   Wayland thread (commands such as `set_clipboard` are never starved).
//! * Mime types are reported in their canonical spelling
//!   ([`kebloop_services::clipboard::canonical_mime`]).
//! * X11 uses XFixes to observe selection ownership and supports bounded INCR transfers.

