/// Extra mime type offered with writes that must not be recorded in history.
pub const TRANSIENT_MIME: &str = "application/x-kebloop-transient";

/// Mime types whose presence marks a selection as secret/transient.
pub const KDE_PASSWORD_HINT_MIME: &str = "x-kde-passwordManagerHint";
pub const CONCEALED_MIME: &str = "application/x-nspasteboard-concealed-type";

/// Canonical text key (every plain-text spelling maps to it).
const TEXT_KEY: &str = "text/plain;charset=utf-8";
const HTML_TYPES: [&str; 1] = ["text/html"];
const RTF_TYPES: [&str; 3] = ["text/rtf", "text/richtext", "application/rtf"];
const IMAGE_TYPES: [&str; 1] = ["image/png"];
const URI_TYPES: [&str; 1] = ["text/uri-list"];
const MARKER_VALUE_LIMIT: usize = 256;

/// Whether a mime type marks the selection as secret, concealed or transient.
pub fn is_sensitive_mime(mime: &str) -> bool {
    let m = mime.to_ascii_lowercase();
    [
        "concealed",
        "transient",
        "autogenerated",
        "passwordmanagerhint",
    ]
    .iter()
    .any(|needle| m.contains(needle))
}

/// Lower-cased spelling without spaces, for matching aliases of our own offers.
fn loose(mime: &str) -> String {
    mime.to_ascii_lowercase().replace(' ', "")
}

/// Which clipboard protocol is usable.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardBackend {
    Gnome,
    X11,
    ExtDataControl,
    WlrDataControl,
    /// No supported protocol; the string explains why (shown in the UI).
    Unavailable(String),
}

impl ClipboardBackend {
    pub fn is_available(&self) -> bool {
        !matches!(self, Self::Unavailable(_))
    }
}

/// Probes the running session without reading or changing the clipboard.
pub fn detect_backend() -> ClipboardBackend {
    let wayland = std::env::var_os("WAYLAND_DISPLAY").is_some_and(|v| !v.is_empty())
        || std::env::var_os("WAYLAND_SOCKET").is_some();
    if !wayland {
        return if std::env::var_os("DISPLAY").is_some_and(|v| !v.is_empty()) {
            x11::probe()
        } else {
            ClipboardBackend::Unavailable("no Wayland or X11 display found".into())
        };
    }
    let conn = match Connection::connect_to_env() {
        Ok(c) => c,
        Err(e) => return ClipboardBackend::Unavailable(format!("cannot connect to Wayland: {e}")),
    };
    match registry_queue_init::<State>(&conn) {
        Ok((globals, _queue)) => {
            let backend = backend_from_globals(&globals);
            if matches!(backend, ClipboardBackend::Unavailable(_))
                && std::env::var("XDG_CURRENT_DESKTOP")
                    .is_ok_and(|v| v.split(':').any(|d| d.eq_ignore_ascii_case("GNOME")))
            {
                gnome::probe()
            } else {
                backend
            }
        }
        Err(e) => ClipboardBackend::Unavailable(format!("cannot enumerate Wayland globals: {e}")),
    }
}

fn backend_from_globals(globals: &GlobalList) -> ClipboardBackend {
    globals.contents().with_list(|list| {
        let has = |name: &str| list.iter().any(|g| g.interface == name);
        if has("ext_data_control_manager_v1") {
            ClipboardBackend::ExtDataControl
        } else if has("zwlr_data_control_manager_v1") {
            ClipboardBackend::WlrDataControl
        } else {
            ClipboardBackend::Unavailable(
                "the compositor offers neither ext-data-control-v1 nor zwlr-data-control-v1 \
                 (for example GNOME/Mutter); clipboard history is unavailable"
                    .into(),
            )
        }
    })
}

#[derive(Debug, thiserror::Error)]
pub enum ClipboardError {
    #[error("clipboard unavailable: {0}")]
    Unavailable(String),
    #[error("wayland error: {0}")]
    Wayland(String),
    #[error("the clipboard thread is not running")]
    NotRunning,
    #[error("the clipboard thread did not answer in time")]
    Timeout,
}

/// Limits and timeouts for reading selections.
#[derive(Debug, Clone)]
pub struct ClipboardConfig {
    pub max_text_bytes: usize,
    pub max_rich_bytes: usize,
    pub max_image_bytes: usize,
    /// Per-type read deadline.
    pub read_timeout: Duration,
    /// Budget for all types of one selection.
    pub total_timeout: Duration,
    /// Use `zwlr_data_control_manager_v1` even when `ext-data-control-v1` is
    /// available (diagnostics and tests).
    pub force_wlr: bool,
    /// Shared "history is recording" flag, kept up to date by the application (settings
    /// change, pause start/expiry). While `false` the watcher reports only the offered mime
    /// types and never requests any data from the source.
    pub recording: Arc<AtomicBool>,
    /// Incremented immediately for external selection changes, including clears, without
    /// waiting for content reads. Own writes leave it unchanged.
    pub revision: Arc<AtomicU64>,
}

impl Default for ClipboardConfig {
    fn default() -> Self {
        Self {
            max_text_bytes: 1024 * 1024,
            max_rich_bytes: 4 * 1024 * 1024,
            max_image_bytes: 32 * 1024 * 1024,
            read_timeout: Duration::from_secs(2),
            total_timeout: Duration::from_secs(5),
            force_wlr: false,
            recording: Arc::new(AtomicBool::new(true)),
            revision: Arc::new(AtomicU64::new(0)),
        }
    }
}

/// A clipboard change.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ClipboardEvent {
    /// Source application identity when the display server exposes it.
    pub source_app: Option<String>,
    /// Every mime type the source offered (including markers), as offered.
    pub mimes: Vec<String>,
    /// Data of the preferred types that were read, keyed by the canonical mime
    /// ([`kebloop_services::clipboard::canonical_mime`]).
    pub data: BTreeMap<String, Vec<u8>>,
    /// A secret/transient marker was present; only marker values are in `data`.
    pub sensitive: bool,
    /// The selection was set by this watcher through `set_clipboard`.
    pub own_write: bool,
    /// Preferred types that were skipped (too large, timed out, read error).
    pub skipped: Vec<String>,
}

