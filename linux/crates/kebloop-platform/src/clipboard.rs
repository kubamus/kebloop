    fn next_event(rx: &async_channel::Receiver<ClipboardEvent>, own: bool) -> ClipboardEvent {
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            assert!(Instant::now() < deadline, "no clipboard event");
            if let Ok(e) = rx.try_recv()
                && e.own_write == own
            {
                return e;
            }
            std::thread::sleep(Duration::from_millis(20));
        }
    }

    fn wl_copy(args: &[&str], stdin: &[u8]) {
        let mut child = std::process::Command::new("wl-copy")
            .args(args)
            .stdin(std::process::Stdio::piped())
            .spawn()
            .unwrap();
        child.stdin.take().unwrap().write_all(stdin).unwrap();
        let _ = child.wait();
    }

    fn private_roundtrip(force_wlr: bool) {
        let cfg = ClipboardConfig {
            max_text_bytes: 4000,
            force_wlr,
            ..ClipboardConfig::default()
        };
        // A selection that exists before the watcher starts is never ingested.
        wl_copy(&[], b"pre-existing");
        let (a, rx) = ClipboardWatcher::start(cfg.clone()).unwrap();
        std::thread::sleep(Duration::from_millis(300));
        assert!(
            rx.try_recv().is_err(),
            "initial selection must not be ingested"
        );
        assert_eq!(
            *a.backend(),
            if force_wlr {
                ClipboardBackend::WlrDataControl
            } else {
                ClipboardBackend::ExtDataControl
            }
        );

        // Own write: served to other clients and reported as own_write.
        let mut data = BTreeMap::new();
        data.insert(
            "text/plain;charset=utf-8".to_owned(),
            b"kebloop-test".to_vec(),
        );
        a.set_clipboard(data, true).unwrap();
        let own = next_event(&rx, true);
        assert_eq!(own.data[TEXT_KEY], b"kebloop-test");
        assert!(own.mimes.iter().any(|m| m == TRANSIENT_MIME));
        assert!(own.sensitive);
        let out = std::process::Command::new("wl-paste")
            .arg("--no-newline")
            .output()
            .unwrap();
        assert_eq!(out.stdout, b"kebloop-test");
        let out = std::process::Command::new("wl-paste")
            .args(["--no-newline", "--type", "UTF8_STRING"])
            .output()
            .unwrap();
        assert_eq!(out.stdout, b"kebloop-test");

        // Foreign text.
        wl_copy(&[], b"foreign-text");
        let e = next_event(&rx, false);
        assert!(!e.sensitive);
        assert_eq!(e.data["text/plain;charset=utf-8"], b"foreign-text");

        // Foreign image bytes.
        wl_copy(&["--type", "image/png"], &[0x89, b'P', b'N', b'G', 1, 2, 3]);
        let e = next_event(&rx, false);
        assert_eq!(e.data["image/png"], [0x89, b'P', b'N', b'G', 1, 2, 3]);

        // Oversize text is skipped, not truncated.
        wl_copy(&[], &vec![b'x'; 9000]);
        let e = next_event(&rx, false);
        assert!(e.data.is_empty(), "{:?}", e.data.keys());
        assert!(!e.skipped.is_empty());

        // Secret marker: only the marker is read, never the text.
        let (b, _rx_b) = ClipboardWatcher::start(cfg).unwrap();
        let mut secret = BTreeMap::new();
        secret.insert("text/plain".to_owned(), b"hunter2".to_vec());
        secret.insert(KDE_PASSWORD_HINT_MIME.to_owned(), b"secret".to_vec());
        b.set_clipboard(secret, false).unwrap();
        let e = next_event(&rx, false);
        assert!(e.sensitive);
        assert_eq!(
            e.data.get("x-kde-passwordmanagerhint").map(Vec::as_slice),
            Some(&b"secret"[..])
        );
        assert!(!e.data.contains_key(TEXT_KEY));
        assert!(e.mimes.iter().any(|m| m == "text/plain"));

        // Replacing the clipboard cancels our source; clearing works.
        a.clear_clipboard().unwrap();
        assert!(a.is_running() && b.is_running());
    }

