fn timespec(d: Duration) -> Timespec {
    Timespec {
        tv_sec: i64::try_from(d.as_secs()).unwrap_or(i64::MAX),
        tv_nsec: i64::from(d.subsec_nanos()),
    }
}

fn wait_fd(fd: BorrowedFd<'_>, flags: PollFlags, timeout: Duration) -> io::Result<bool> {
    loop {
        let mut fds = [PollFd::new(&fd, flags)];
        match poll(&mut fds, Some(&timespec(timeout))) {
            Ok(n) => return Ok(n > 0),
            Err(Errno::INTR) => continue,
            Err(e) => return Err(e.into()),
        }
    }
}

#[derive(Debug, PartialEq, Eq)]
enum ReadOutcome {
    Data(Vec<u8>),
    TooLarge,
    TimedOut,
    Failed,
}

/// Reads `fd` until EOF with a size cap and an overall deadline.
fn read_limited(fd: &OwnedFd, max: usize, deadline: Instant) -> ReadOutcome {
    if fcntl_setfl(fd, OFlags::NONBLOCK).is_err() {
        return ReadOutcome::Failed;
    }
    let mut out = Vec::new();
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        let now = Instant::now();
        if now >= deadline {
            return ReadOutcome::TimedOut;
        }
        match wait_fd(fd.as_fd(), PollFlags::IN, deadline - now) {
            Ok(true) => {}
            Ok(false) => return ReadOutcome::TimedOut,
            Err(_) => return ReadOutcome::Failed,
        }
        match rustix::io::read(fd, &mut buf) {
            Ok(0) => return ReadOutcome::Data(out),
            Ok(n) => {
                if out.len() + n > max {
                    return ReadOutcome::TooLarge;
                }
                out.extend_from_slice(&buf[..n]);
            }
            Err(Errno::AGAIN | Errno::INTR) => {}
            Err(_) => return ReadOutcome::Failed,
        }
    }
}

fn write_all_timeout(fd: &OwnedFd, mut data: &[u8], timeout: Duration) -> io::Result<()> {
    fcntl_setfl(fd, OFlags::NONBLOCK)?;
    let deadline = Instant::now() + timeout;
    while !data.is_empty() {
        match rustix::io::write(fd, data) {
            Ok(n) => data = &data[n..],
            Err(Errno::AGAIN | Errno::INTR) => {
                let now = Instant::now();
                if now >= deadline {
                    return Err(io::ErrorKind::TimedOut.into());
                }
                wait_fd(fd.as_fd(), PollFlags::OUT, deadline - now)?;
            }
            Err(e) => return Err(e.into()),
        }
    }
    Ok(())
}

