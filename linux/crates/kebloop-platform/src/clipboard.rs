/// One data request decided by [`plan_reads`].
#[derive(Debug, Clone, PartialEq, Eq)]
struct ReadItem {
    /// Mime type exactly as offered (used for the `receive` request).
    offered: String,
    /// Canonical key under which the data is reported.
    key: String,
    max: usize,
    /// Legacy X11 `STRING`: Latin-1 unless the bytes happen to be UTF-8.
    latin1: bool,
}

/// What to read from an offer.
#[derive(Debug, Clone, PartialEq, Eq)]
struct ReadPlan {
    sensitive: bool,
    items: Vec<ReadItem>,
}

/// Decides which mime types to request. Pure: no I/O. Nothing is requested while `recording` is
/// off, and a secret marker restricts the plan to the (short) marker values.
fn plan_reads(mimes: &[String], cfg: &ClipboardConfig, recording: bool) -> ReadPlan {
    let sensitive = mimes.iter().any(|m| is_sensitive_mime(m));
    let mut items = Vec::new();
    if !recording {
        return ReadPlan { sensitive, items };
    }
    if sensitive {
        // Read the marker values only; never the content.
        for mime in mimes.iter().filter(|m| is_sensitive_mime(m)) {
            items.push(ReadItem {
                offered: mime.clone(),
                key: canonical_mime(mime),
                max: MARKER_VALUE_LIMIT,
                latin1: false,
            });
        }
        return ReadPlan { sensitive, items };
    }
    let mut push = |offered: &String, max: usize| {
        let key = canonical_mime(offered);
        if !items.iter().any(|i: &ReadItem| i.key == key) {
            items.push(ReadItem {
                offered: offered.clone(),
                latin1: offered.trim().eq_ignore_ascii_case("string"),
                key,
                max,
            });
        }
    };
    if let Some(best) = mimes
        .iter()
        .filter_map(|m| text_rank(m).map(|rank| (rank, m)))
        .min_by_key(|(rank, _)| *rank)
        .map(|(_, m)| m)
    {
        push(best, cfg.max_text_bytes);
    }
    let groups: [(&[&str], usize); 4] = [
        (&HTML_TYPES, cfg.max_rich_bytes),
        (&RTF_TYPES, cfg.max_rich_bytes),
        (&URI_TYPES, cfg.max_text_bytes),
        (&IMAGE_TYPES, cfg.max_image_bytes),
    ];
    for (group, max) in groups {
        let found = group
            .iter()
            .find_map(|wanted| mimes.iter().find(|m| canonical_mime(m) == *wanted));
        if let Some(mime) = found {
            push(mime, max);
        }
    }
    ReadPlan { sensitive, items }
}

fn latin1_to_utf8(bytes: &[u8]) -> Vec<u8> {
    if std::str::from_utf8(bytes).is_ok() {
        return bytes.to_vec();
    }
    bytes
        .iter()
        .map(|&b| char::from(b))
        .collect::<String>()
        .into_bytes()
}

/// A requested mime type whose bytes are still arriving through `reader`.
struct PendingRead {
    item: ReadItem,
    reader: OwnedFd,
}

/// Work for the reader thread, kept in selection order.
enum Job {
    /// Nothing left to read.
    Ready(ClipboardEvent),
    /// Collect the pipes into `base` (which already carries mimes and flags).
    Read {
        base: ClipboardEvent,
        pending: Vec<PendingRead>,
        started: Instant,
    },
}

/// Issues the `receive` requests for a new selection (Wayland thread, never blocks on the
/// source) and returns the job that collects the data.
fn prepare_job(
    conn: &Connection,
    offer: &Offer,
    cfg: &ClipboardConfig,
    own: Option<&OwnSource>,
) -> Job {
    let mut mimes = offer.mimes();
    if let Some(own) = own.filter(|o| mimes.contains(&o.marker)) {
        mimes.retain(|m| *m != own.marker);
        let mut data = BTreeMap::new();
        for (key, value) in &own.payload.items {
            data.entry(canonical_mime(key))
                .or_insert_with(|| value.as_ref().clone());
        }
        let sensitive = mimes.iter().any(|m| is_sensitive_mime(m)) || own.transient;
        return Job::Ready(ClipboardEvent {
            mimes,
            data,
            sensitive,
            own_write: true,
            source_app: None,
            skipped: Vec::new(),
        });
    }

    let plan = plan_reads(&mimes, cfg, cfg.recording.load(Ordering::Relaxed));
    let mut base = ClipboardEvent {
        sensitive: plan.sensitive,
        mimes,
        ..ClipboardEvent::default()
    };
    let started = Instant::now();
    let mut pending = Vec::new();
    for item in plan.items {
        let Ok((reader, writer)) = pipe_with(PipeFlags::CLOEXEC) else {
            base.skipped.push(item.key);
            continue;
        };
        offer.receive(&item.offered, writer.as_fd());
        drop(writer);
        pending.push(PendingRead { item, reader });
    }
    if !pending.is_empty() && conn.flush().is_err() {
        base.skipped
            .extend(pending.drain(..).map(|read| read.item.key));
    }
    if pending.is_empty() {
        Job::Ready(base)
    } else {
        Job::Read {
            base,
            pending,
            started,
        }
    }
}

/// Reads the pipes of a job (reader thread; blocks, with deadlines).
fn finish_job(job: Job, cfg: &ClipboardConfig) -> ClipboardEvent {
    match job {
        Job::Ready(event) => event,
        Job::Read {
            mut base,
            pending,
            started,
        } => {
            for read in pending {
                let deadline = (Instant::now() + cfg.read_timeout).min(started + cfg.total_timeout);
                match read_limited(&read.reader, read.item.max, deadline) {
                    ReadOutcome::Data(bytes) => {
                        let bytes = if read.item.latin1 {
                            latin1_to_utf8(&bytes)
                        } else {
                            bytes
                        };
                        base.data.insert(read.item.key, bytes);
                    }
                    _ => base.skipped.push(read.item.key),
                }
            }
            base
        }
    }
}

