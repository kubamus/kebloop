//! Clipboard history store.
//!
//! The store never touches the clipboard: the platform layer offers each clipboard change as a
//! `mime type -> bytes` map plus the current time. Persistence is a JSON file plus an attachment
//! directory, both private to the user (files 0600, directories 0700).

