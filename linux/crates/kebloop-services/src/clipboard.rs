use std::fs;
use std::io::ErrorKind;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};

use crate::error::ConfigError;
use crate::l10n::Localizer;
use crate::persist::DebouncedWriter;
use crate::util::{atomic_write, corrupt_destination, create_dir_all_mode, new_id};

/// Maximum accepted plain-text size in UTF-8 bytes.
pub const TEXT_BYTE_LIMIT: usize = 100 * 1024;
/// Per-entry attachment budget.
pub const MAX_ATTACHMENT_BYTES_PER_ENTRY: usize = 5 * 1024 * 1024;
/// Total attachment budget across the history.
pub const MAX_ATTACHMENT_STORAGE_BYTES: usize = 50 * 1024 * 1024;
/// Maximum number of pinned entries.
pub const MAX_PINNED: usize = 50;
/// Maximum number of unpinned entries (upper bound of the user setting).
pub const MAX_ITEM_COUNT: usize = 200;
/// Maximum retention in days.
pub const MAX_AGE_DAYS: u32 = 3650;
/// Longest accepted pause.
pub const MAX_PAUSE: Duration = Duration::from_secs(7 * 24 * 60 * 60);
const MAX_STORAGE_BYTES: u64 = (250 * (TEXT_BYTE_LIMIT * 6 + 1_024)) as u64;
/// Seconds between the Unix epoch and 2001-01-01 (the Apple reference date used on disk).
const REFERENCE_OFFSET: f64 = 978_307_200.0;

/// Plain-text MIME types in order of preference.
pub const TEXT_TYPES: &[&str] = &[
    "text/plain;charset=utf-8",
    "text/plain",
    "UTF8_STRING",
    "STRING",
    "TEXT",
];
/// Image MIME types in order of preference.
pub const IMAGE_TYPES: &[&str] = &[
    "image/png",
    "image/tiff",
    "image/jpeg",
    "image/heic",
    "image/gif",
    "image/webp",
    "image/bmp",
];
/// Rich-text MIME types in order of preference.
pub const RICH_TEXT_TYPES: &[&str] = &["text/rtf", "application/rtf", "text/richtext", "text/html"];
/// MIME type used when putting plain text back on the clipboard.
pub const TEXT_OUTPUT_TYPE: &str = "text/plain;charset=utf-8";
const KDE_HINT: &str = "x-kde-passwordmanagerhint";
const SENSITIVE_MARKERS: &[&str] = &["concealed", "transient", "autogenerated", "password"];

/// Clipboard offer: MIME type to bytes.
pub type ClipboardFormats = BTreeMap<String, Vec<u8>>;

/// Canonical spelling of a clipboard MIME type, used as the key of [`ClipboardFormats`] and for
/// every lookup in the store:
///
/// * type, subtype and parameter names are lower-cased, spaces around `;` and `=` are removed;
/// * `charset` values are lower-cased and `utf8` / `us-ascii` become `utf-8`;
/// * the X11 text atoms `UTF8_STRING`, `STRING`, `TEXT` and every UTF-8 `text/plain` spelling
///   become [`TEXT_OUTPUT_TYPE`] (`text/plain;charset=utf-8`);
/// * a `charset=utf-8` parameter is dropped from other types (`text/html;charset=utf-8` is
///   `text/html`).
pub fn canonical_mime(raw: &str) -> String {
    let trimmed = raw.trim();
    if ["utf8_string", "string", "text"]
        .iter()
        .any(|atom| trimmed.eq_ignore_ascii_case(atom))
    {
        return TEXT_OUTPUT_TYPE.to_owned();
    }
    let mut parts = trimmed.split(';');
    let essence = parts.next().unwrap_or("").trim().to_ascii_lowercase();
    let mut params: Vec<String> = Vec::new();
    let mut utf8 = true;
    for part in parts {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        let (key, value) = part.split_once('=').unwrap_or((part, ""));
        let key = key.trim().to_ascii_lowercase();
        let value = value.trim().trim_matches('"').trim();
        if key == "charset" {
            let charset = value.to_ascii_lowercase();
            if matches!(charset.as_str(), "utf-8" | "utf8" | "us-ascii") {
                continue;
            }
            utf8 = false;
            params.push(format!("charset={charset}"));
        } else {
            params.push(format!("{key}={}", value.to_ascii_lowercase()));
        }
    }
    if essence == "text/plain" && utf8 && params.is_empty() {
        return TEXT_OUTPUT_TYPE.to_owned();
    }
    if essence == "text/plain" && utf8 {
        params.insert(0, "charset=utf-8".to_owned());
    }
    if params.is_empty() {
        essence
    } else {
        format!("{essence};{}", params.join(";"))
    }
}

/// Preference of a raw plain-text MIME spelling (lower is better); `None` for other types.
pub fn text_rank(raw: &str) -> Option<usize> {
    if canonical_mime(raw) != TEXT_OUTPUT_TYPE {
        return None;
    }
    let lowered = raw.trim().to_ascii_lowercase();
    Some(match lowered.as_str() {
        "utf8_string" => 2,
        "string" => 3,
        "text" => 4,
        other if other.contains(';') => 0,
        _ => 1,
    })
}

/// The bytes stored under any spelling of `wanted` (compared canonically).
fn find_format<'a>(formats: &'a ClipboardFormats, wanted: &str) -> Option<&'a [u8]> {
    if let Some(data) = formats.get(wanted) {
        return Some(data);
    }
    let wanted = canonical_mime(wanted);
    formats
        .iter()
        .find(|(name, _)| canonical_mime(name) == wanted)
        .map(|(_, data)| data.as_slice())
}

/// Files used by the store.
#[derive(Debug, Clone)]
pub struct ClipboardPaths {
    /// History JSON (`clipboard-history.json`).
    pub history_file: PathBuf,
    /// Attachment directory (`clipboard-attachments/`).
    pub attachments_dir: PathBuf,
    /// Settings JSON (`clipboard-settings.json`).
    pub settings_file: PathBuf,
}

impl ClipboardPaths {
    /// Standard layout inside `$XDG_DATA_HOME/kebloop/`.
    pub fn in_dir(dir: &Path) -> Self {
        Self {
            history_file: dir.join("clipboard-history.json"),
            attachments_dir: dir.join("clipboard-attachments"),
            settings_file: dir.join("clipboard-settings.json"),
        }
    }
}

/// Kind of stored attachment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum AttachmentKind {
    /// Image data.
    Image,
    /// RTF or HTML.
    RichText,
}

/// Metadata of an attachment stored as a separate file.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardAttachment {
    /// File name inside the attachment directory (`clipboard-<uuid>.bin`).
    pub file_name: String,
    /// MIME type the data had on the clipboard (the field keeps the macOS key name).
    pub pasteboard_type: String,
    /// Exact size in bytes.
    pub byte_count: usize,
    /// Attachment kind.
    pub kind: AttachmentKind,
}

/// One history entry.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardEntry {
    /// Stable identifier.
    pub id: String,
    /// Plain text (may be empty for image-only entries).
    #[serde(default)]
    pub text: String,
    /// Seconds since 2001-01-01 UTC (the format of the macOS history file).
    pub date: f64,
    /// Pinned entries survive age and count retention.
    #[serde(default)]
    pub is_pinned: bool,
    /// Application that owned the clipboard, when known.
    #[serde(
        default,
        rename = "sourceBundleIdentifier",
        skip_serializing_if = "Option::is_none"
    )]
    pub source_app: Option<String>,
    /// Image attachment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image_attachment: Option<ClipboardAttachment>,
    /// Rich-text attachment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rich_text_attachment: Option<ClipboardAttachment>,
}

impl ClipboardEntry {
    /// Text-only entry.
    pub fn new(id: impl Into<String>, text: impl Into<String>, at: SystemTime) -> Self {
        Self {
            id: id.into(),
            text: text.into(),
            date: to_reference(at),
            is_pinned: false,
            source_app: None,
            image_attachment: None,
            rich_text_attachment: None,
        }
    }

    /// Time the entry was recorded.
    pub fn time(&self) -> SystemTime {
        from_reference(self.date)
    }

    /// One-line preview (first 240 characters, whitespace collapsed) or a localized placeholder.
    pub fn preview(&self, localizer: &Localizer) -> String {
        let head: String = self.text.chars().take(240).collect();
        let flattened = head.split_whitespace().collect::<Vec<_>>().join(" ");
        if !flattened.is_empty() {
            return flattened;
        }
        match (&self.image_attachment, &self.rich_text_attachment) {
            (Some(_), Some(_)) => localizer.tr("Image and rich text"),
            (Some(_), None) => localizer.tr("Image"),
            (None, Some(_)) => localizer.tr("Rich text"),
            (None, None) => localizer.tr("Clipboard item"),
        }
    }

    /// Text used for filtering.
    pub fn searchable_text(&self, localizer: &Localizer) -> String {
        if self.text.is_empty() {
            self.preview(localizer)
        } else {
            self.text.clone()
        }
    }

    /// Whether the entry carries anything worth keeping.
    pub fn has_content(&self) -> bool {
        !self.text.trim().is_empty()
            || self.image_attachment.is_some()
            || self.rich_text_attachment.is_some()
    }
}

fn to_reference(time: SystemTime) -> f64 {
    let unix = match time.duration_since(UNIX_EPOCH) {
        Ok(d) => d.as_secs_f64(),
        Err(e) => -e.duration().as_secs_f64(),
    };
    unix - REFERENCE_OFFSET
}

fn from_reference(seconds: f64) -> SystemTime {
    let unix = seconds + REFERENCE_OFFSET;
    if !unix.is_finite() {
        return UNIX_EPOCH;
    }
    if unix >= 0.0 {
        UNIX_EPOCH + Duration::from_secs_f64(unix.min(1e12))
    } else {
        UNIX_EPOCH - Duration::from_secs_f64((-unix).min(1e12))
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Settings {
    enabled: bool,
    maximum_item_count: usize,
    maximum_age_days: u32,
    excluded_sources: BTreeSet<String>,
    pause_until: Option<f64>,
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            enabled: true,
            maximum_item_count: MAX_ITEM_COUNT,
            maximum_age_days: 0,
            excluded_sources: BTreeSet::new(),
            pause_until: None,
        }
    }
}

/// Why an offered clipboard change was not recorded.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IgnoreReason {
    /// History recording is switched off.
    Disabled,
    /// Recording is paused.
    Paused,
    /// A password-manager / concealed marker was present.
    Sensitive,
    /// The source application is excluded.
    ExcludedSource,
    /// Nothing storable (blank text, no valid or in-budget attachment).
    Empty,
}

/// Outcome of [`ClipboardStore::record`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RecordOutcome {
    /// Stored (or moved to the front) under this id.
    Recorded(String),
    /// Not stored.
    Ignored(IgnoreReason),
}

/// Formats to put back on the clipboard for an entry.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ClipboardPayload {
    /// `(mime type, bytes)` pairs: text, rich text, image.
    pub formats: Vec<(String, Vec<u8>)>,
}

/// Whether an offer carries a sensitive-content marker. `x-kde-passwordManagerHint` counts when
/// its value is `secret` (or empty/unreadable); the macOS concealed, transient and auto-generated
/// markers always count.
pub fn is_sensitive(formats: &ClipboardFormats) -> bool {
    formats.iter().any(|(name, data)| {
        let lowered = name.to_lowercase();
        if lowered == KDE_HINT {
            let value = String::from_utf8_lossy(data);
            let value = value.trim();
            return value.is_empty() || value.eq_ignore_ascii_case("secret");
        }
        SENSITIVE_MARKERS.iter().any(|m| lowered.contains(m))
    })
}

fn is_valid_image(data: &[u8]) -> bool {
    if data.is_empty() || data.len() > MAX_ATTACHMENT_BYTES_PER_ENTRY {
        return false;
    }
    let trimmed_end = data.iter().rposition(|b| *b != 0).map_or(0, |i| i + 1);
    if data.starts_with(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A]) {
        return data.ends_with(&[b'I', b'E', b'N', b'D', 0xAE, 0x42, 0x60, 0x82]);
    }
    if data.starts_with(&[0xFF, 0xD8, 0xFF]) {
        return data[..trimmed_end].ends_with(&[0xFF, 0xD9]);
    }
    if data.starts_with(b"GIF87a") || data.starts_with(b"GIF89a") {
        return data[..trimmed_end].ends_with(&[0x3B]);
    }
    if data.starts_with(&[b'I', b'I', 0x2A, 0x00]) || data.starts_with(&[b'M', b'M', 0x00, 0x2A]) {
        return true;
    }
    if data.starts_with(b"BM") {
        return data.len() > 14;
    }
    if data.len() > 12 && data.starts_with(b"RIFF") && &data[8..12] == b"WEBP" {
        return true;
    }
    data.len() > 12 && &data[4..8] == b"ftyp"
}

fn is_valid_rich_text(data: &[u8]) -> bool {
    if data.is_empty() || data.len() > MAX_ATTACHMENT_BYTES_PER_ENTRY {
        return false;
    }
    if data
        .iter()
        .take(32)
        .copied()
        .collect::<Vec<_>>()
        .starts_with(b"{\\rtf")
    {
        return true;
    }
    std::str::from_utf8(data).is_ok_and(|text| !text.trim().is_empty())
}

fn is_valid_attachment(data: &[u8], kind: AttachmentKind) -> bool {
    match kind {
        AttachmentKind::Image => is_valid_image(data),
        AttachmentKind::RichText => is_valid_rich_text(data),
    }
}

fn is_safe_attachment_name(name: &str) -> bool {
    !name.contains('/')
        && name.starts_with("clipboard-")
        && name.ends_with(".bin")
        && name.chars().count() < 100
}

fn first_payload<'a>(
    formats: &'a ClipboardFormats,
    accepted: &'a [&'a str],
    kind: AttachmentKind,
) -> Option<(&'a str, &'a [u8])> {
    accepted.iter().find_map(|mime| {
        let data = find_format(formats, mime)?;
        (!data.is_empty()
            && data.len() <= MAX_ATTACHMENT_BYTES_PER_ENTRY
            && is_valid_attachment(data, kind))
        .then_some((*mime, data))
    })
}

/// The plain text of an offer, empty when there is none or when it exceeds [`TEXT_BYTE_LIMIT`].
fn extract_text(formats: &ClipboardFormats) -> String {
    let best = formats
        .iter()
        .filter_map(|(name, data)| text_rank(name).map(|rank| (rank, data)))
        .min_by_key(|(rank, _)| *rank);
    match best {
        Some((_, data)) if data.len() <= TEXT_BYTE_LIMIT => {
            String::from_utf8_lossy(data).into_owned()
        }
        _ => String::new(),
    }
}

fn attachment_bytes(entry: &ClipboardEntry) -> usize {
    entry.image_attachment.as_ref().map_or(0, |a| a.byte_count)
        + entry
            .rich_text_attachment
            .as_ref()
            .map_or(0, |a| a.byte_count)
}

fn retained(
    entries: &[ClipboardEntry],
    maximum_item_count: usize,
    maximum_age_days: u32,
    now: SystemTime,
) -> Vec<ClipboardEntry> {
    let cutoff =
        (maximum_age_days > 0).then(|| to_reference(now) - f64::from(maximum_age_days) * 86_400.0);
    let mut seen = BTreeSet::new();
    let mut sorted: Vec<&ClipboardEntry> = entries.iter().collect();
    sorted.sort_by(|a, b| b.date.total_cmp(&a.date));
    let valid: Vec<&ClipboardEntry> = sorted
        .into_iter()
        .filter(|e| {
            e.has_content()
                && e.text.len() <= TEXT_BYTE_LIMIT
                && seen.insert(e.id.clone())
                && (e.is_pinned || cutoff.is_none_or(|c| e.date >= c))
        })
        .collect();
    let mut result: Vec<ClipboardEntry> = valid
        .iter()
        .filter(|e| e.is_pinned)
        .map(|e| (*e).clone())
        .collect();
    result.extend(
        valid
            .iter()
            .filter(|e| !e.is_pinned)
            .take(maximum_item_count)
            .map(|e| (*e).clone()),
    );
    result.sort_by(|a, b| b.date.total_cmp(&a.date));
    result
}

fn ensure_private_dir(dir: &Path) -> Result<(), ConfigError> {
    create_dir_all_mode(dir, 0o700)?;
    fs::set_permissions(dir, fs::Permissions::from_mode(0o700)).map_err(|e| ConfigError::io(dir, e))
}

/// The clipboard history.
#[derive(Debug)]
pub struct ClipboardStore {
    paths: ClipboardPaths,
    settings: Settings,
    items: Vec<ClipboardEntry>,
    recovered_corrupt: Option<PathBuf>,
    /// Why history is switched off for this run (the store could not be opened).
    unavailable: Option<String>,
    /// Debounced background writer for the history file.
    writer: Option<Arc<DebouncedWriter>>,
}

impl ClipboardStore {
    /// A store that records nothing and never touches the disk. Used when [`ClipboardStore::open`]
    /// failed, so the launcher still starts; `reason` is shown to the user.
    pub fn unavailable(paths: ClipboardPaths, reason: impl Into<String>) -> Self {
        Self {
            paths,
            settings: Settings {
                enabled: false,
                ..Settings::default()
            },
            items: Vec::new(),
            recovered_corrupt: None,
            unavailable: Some(reason.into()),
            writer: None,
        }
    }

    /// Why history is unavailable for this run, if it is (see [`ClipboardStore::unavailable`]).
    pub fn unavailable_reason(&self) -> Option<&str> {
        self.unavailable.as_deref()
    }

    /// Write the history file from a background thread, coalescing bursts of changes.
    pub fn set_deferred_writer(&mut self, writer: Arc<DebouncedWriter>) {
        self.writer = Some(writer);
    }

    /// Write a pending history update now (call on quit).
    pub fn flush(&self) -> Result<(), ConfigError> {
        self.writer.as_ref().map_or(Ok(()), |w| w.flush())
    }

    /// Load settings and history. Corrupt files are moved aside (`*.corrupt`), invalid or missing
    /// attachments are dropped from their entries, and orphaned attachment files are deleted.
    pub fn open(paths: ClipboardPaths, now: SystemTime) -> Result<Self, ConfigError> {
        let mut settings = match fs::read(&paths.settings_file) {
            Ok(bytes) => serde_json::from_slice::<Settings>(&bytes).unwrap_or_default(),
            Err(_) => Settings::default(),
        };
        settings.maximum_item_count = settings.maximum_item_count.clamp(1, MAX_ITEM_COUNT);
        settings.maximum_age_days = settings.maximum_age_days.min(MAX_AGE_DAYS);
        if settings
            .pause_until
            .is_some_and(|d| from_reference(d) <= now)
        {
            settings.pause_until = None;
        }
        let mut store = Self {
            paths,
            settings,
            items: Vec::new(),
            recovered_corrupt: None,
            unavailable: None,
            writer: None,
        };
        let original = store.load_history();
        let decoded = original.unwrap_or_default();
        let sanitized = sanitize(&decoded, &store.paths.attachments_dir);
        store.items = retained(
            &sanitized,
            store.settings.maximum_item_count,
            store.settings.maximum_age_days,
            now,
        );
        store.save_settings()?;
        store.cleanup_attachments();
        if store.items != decoded {
            store.persist()?;
        }
        Ok(store)
    }

    fn load_history(&mut self) -> Option<Vec<ClipboardEntry>> {
        let path = &self.paths.history_file;
        let meta = fs::metadata(path).ok()?;
        let parsed = if meta.len() > MAX_STORAGE_BYTES {
            None
        } else {
            fs::read(path)
                .ok()
                .and_then(|b| serde_json::from_slice::<Vec<ClipboardEntry>>(&b).ok())
        };
        if parsed.is_none() {
            let aside = corrupt_destination(path);
            if fs::rename(path, &aside).is_ok() {
                self.recovered_corrupt = Some(aside);
            }
        }
        parsed
    }

    /// Path of the corrupt history file set aside while opening, if any.
    pub fn recovered_corrupt_file(&self) -> Option<&Path> {
        self.recovered_corrupt.as_deref()
    }

    /// Entries, newest first.
    pub fn items(&self) -> &[ClipboardEntry] {
        &self.items
    }

    /// Whether recording is switched on.
    pub fn is_enabled(&self) -> bool {
        self.settings.enabled && self.unavailable.is_none()
    }

    /// Whether recording is currently paused.
    pub fn is_paused(&self, now: SystemTime) -> bool {
        self.settings
            .pause_until
            .is_some_and(|d| from_reference(d) > now)
    }

    /// Enabled and not paused.
    pub fn is_recording(&self, now: SystemTime) -> bool {
        self.is_enabled() && !self.is_paused(now)
    }

    /// Persisted pause deadline.
    pub fn pause_deadline(&self) -> Option<SystemTime> {
        self.settings.pause_until.map(from_reference)
    }

    /// Maximum unpinned entries.
    pub fn maximum_item_count(&self) -> usize {
        self.settings.maximum_item_count
    }

    /// Retention in days (0 keeps entries indefinitely).
    pub fn maximum_age_days(&self) -> u32 {
        self.settings.maximum_age_days
    }

    /// Source applications whose copies are not recorded.
    pub fn excluded_sources(&self) -> &BTreeSet<String> {
        &self.settings.excluded_sources
    }

    fn save_settings(&self) -> Result<(), ConfigError> {
        if let Some(reason) = &self.unavailable {
            return Err(ConfigError::invalid(format!(
                "Clipboard history is unavailable: {reason}"
            )));
        }
        if let Some(dir) = self.paths.settings_file.parent() {
            ensure_private_dir(dir)?;
        }
        atomic_write(
            &self.paths.settings_file,
            &serde_json::to_vec_pretty(&self.settings)?,
            0o600,
        )
    }

    /// Turn recording on or off.
    pub fn set_enabled(&mut self, enabled: bool) -> Result<(), ConfigError> {
        self.settings.enabled = enabled;
        self.save_settings()
    }

    /// Set the unpinned-entry limit (clamped to 1 to 200) and apply it.
    pub fn set_maximum_item_count(
        &mut self,
        count: usize,
        now: SystemTime,
    ) -> Result<(), ConfigError> {
        self.settings.maximum_item_count = count.clamp(1, MAX_ITEM_COUNT);
        self.save_settings()?;
        self.enforce_retention(now)
    }

    /// Set the retention in days (clamped to 0 to 3650) and apply it.
    pub fn set_maximum_age_days(&mut self, days: u32, now: SystemTime) -> Result<(), ConfigError> {
        self.settings.maximum_age_days = days.min(MAX_AGE_DAYS);
        self.save_settings()?;
        self.enforce_retention(now)
    }

    /// Replace the excluded source applications.
    pub fn set_excluded_sources(&mut self, sources: BTreeSet<String>) -> Result<(), ConfigError> {
        self.settings.excluded_sources = sources;
        self.save_settings()
    }

    /// Pause for `interval` (capped at 7 days); a zero interval resumes.
    pub fn pause_for(&mut self, interval: Duration, now: SystemTime) -> Result<(), ConfigError> {
        if interval.is_zero() {
            return self.resume();
        }
        self.settings.pause_until = Some(to_reference(now + interval.min(MAX_PAUSE)));
        self.save_settings()
    }

    /// Pause until `deadline` (capped at 7 days from now); a past deadline resumes.
    pub fn pause_until(
        &mut self,
        deadline: SystemTime,
        now: SystemTime,
    ) -> Result<(), ConfigError> {
        if deadline <= now {
            return self.resume();
        }
        self.settings.pause_until = Some(to_reference(deadline.min(now + MAX_PAUSE)));
        self.save_settings()
    }

    /// Resume recording.
    pub fn resume(&mut self) -> Result<(), ConfigError> {
        if self.settings.pause_until.take().is_some() {
            self.save_settings()?;
        }
        Ok(())
    }

    /// Periodic maintenance: expire a finished pause and apply retention.
    pub fn tick(&mut self, now: SystemTime) -> Result<(), ConfigError> {
        if self
            .settings
            .pause_until
            .is_some_and(|d| from_reference(d) <= now)
        {
            self.settings.pause_until = None;
            self.save_settings()?;
        }
        self.enforce_retention(now)
    }

    /// Offer a clipboard change. `source_app` is the owning application when it is known.
    pub fn record(
        &mut self,
        formats: &ClipboardFormats,
        source_app: Option<&str>,
        now: SystemTime,
    ) -> Result<RecordOutcome, ConfigError> {
        if self.unavailable.is_some() {
            return Ok(RecordOutcome::Ignored(IgnoreReason::Disabled));
        }
        self.tick(now)?;
        if !self.settings.enabled {
            return Ok(RecordOutcome::Ignored(IgnoreReason::Disabled));
        }
        if self.is_paused(now) {
            return Ok(RecordOutcome::Ignored(IgnoreReason::Paused));
        }
        if is_sensitive(formats) {
            return Ok(RecordOutcome::Ignored(IgnoreReason::Sensitive));
        }
        if source_app.is_some_and(|s| self.settings.excluded_sources.contains(s)) {
            return Ok(RecordOutcome::Ignored(IgnoreReason::ExcludedSource));
        }
        // Like the macOS store, drop an oversized text representation while still allowing its
        // bounded rich-text or image payload through.
        let text = extract_text(formats);
        let image = first_payload(formats, IMAGE_TYPES, AttachmentKind::Image);
        let rich = first_payload(formats, RICH_TEXT_TYPES, AttachmentKind::RichText);
        if text.trim().is_empty() && image.is_none() && rich.is_none() {
            return Ok(RecordOutcome::Ignored(IgnoreReason::Empty));
        }

        let existing = if text.is_empty() {
            None
        } else {
            self.items.iter().find(|i| i.text == text).cloned()
        };
        let id = existing.as_ref().map_or_else(new_id, |e| e.id.clone());
        let others: usize = self.items.iter().map(attachment_bytes).sum::<usize>()
            - existing.as_ref().map_or(0, attachment_bytes);
        let mut total = others;
        let mut entry_bytes = 0usize;
        let mut image_attachment = None;
        let mut rich_attachment = None;
        if let Some((mime, data)) = image
            && data.len() <= MAX_ATTACHMENT_BYTES_PER_ENTRY
            && total + data.len() <= MAX_ATTACHMENT_STORAGE_BYTES
        {
            image_attachment = self.save_attachment(data, mime, AttachmentKind::Image);
            if image_attachment.is_some() {
                entry_bytes += data.len();
                total += data.len();
            }
        }
        if let Some((mime, data)) = rich
            && data.len() <= MAX_ATTACHMENT_BYTES_PER_ENTRY - entry_bytes
            && total + data.len() <= MAX_ATTACHMENT_STORAGE_BYTES
        {
            rich_attachment = self.save_attachment(data, mime, AttachmentKind::RichText);
        }
        let entry = ClipboardEntry {
            id: id.clone(),
            text,
            date: to_reference(now),
            is_pinned: existing.as_ref().is_some_and(|e| e.is_pinned),
            source_app: source_app.map(str::to_string),
            image_attachment,
            rich_text_attachment: rich_attachment,
        };
        if !entry.has_content() {
            self.cleanup_attachments();
            return Ok(RecordOutcome::Ignored(IgnoreReason::Empty));
        }
        self.items.retain(|i| i.id != id);
        self.items.insert(0, entry);
        self.items = retained(
            &self.items,
            self.settings.maximum_item_count,
            self.settings.maximum_age_days,
            now,
        );
        self.persist()?;
        Ok(RecordOutcome::Recorded(id))
    }

    /// Delete every entry, including pinned ones, and their attachment files.
    pub fn clear(&mut self) -> Result<(), ConfigError> {
        self.items.clear();
        self.persist()
    }

    /// Delete all unpinned entries.
    pub fn clear_unpinned(&mut self) -> Result<(), ConfigError> {
        self.items.retain(|i| i.is_pinned);
        self.persist()
    }

    /// Delete one entry.
    pub fn remove(&mut self, id: &str) -> Result<(), ConfigError> {
        self.items.retain(|i| i.id != id);
        self.persist()
    }

    /// Pin or unpin. Returns `Ok(false)` when the entry is unknown or 50 entries are already
    /// pinned.
    pub fn set_pinned(
        &mut self,
        id: &str,
        pinned: bool,
        now: SystemTime,
    ) -> Result<bool, ConfigError> {
        let Some(index) = self.items.iter().position(|i| i.id == id) else {
            return Ok(false);
        };
        if pinned
            && !self.items[index].is_pinned
            && self.items.iter().filter(|i| i.is_pinned).count() >= MAX_PINNED
        {
            return Ok(false);
        }
        if self.items[index].is_pinned == pinned {
            return Ok(true);
        }
        self.items[index].is_pinned = pinned;
        self.items = retained(
            &self.items,
            self.settings.maximum_item_count,
            self.settings.maximum_age_days,
            now,
        );
        self.persist()?;
        Ok(true)
    }

    /// Toggle the pin state; same return value as [`ClipboardStore::set_pinned`].
    pub fn toggle_pin(&mut self, id: &str, now: SystemTime) -> Result<bool, ConfigError> {
        let Some(current) = self.items.iter().find(|i| i.id == id).map(|i| i.is_pinned) else {
            return Ok(false);
        };
        self.set_pinned(id, !current, now)
    }

    fn enforce_retention(&mut self, now: SystemTime) -> Result<(), ConfigError> {
        let kept = retained(
            &self.items,
            self.settings.maximum_item_count,
            self.settings.maximum_age_days,
            now,
        );
        if kept != self.items {
            self.items = kept;
            self.persist()?;
        }
        Ok(())
    }

    /// Formats to put on the clipboard for an entry: text, rich text, then image. Attachments that
    /// fail validation are removed from the entry.
    pub fn payload_for(&mut self, id: &str) -> Result<Option<ClipboardPayload>, ConfigError> {
        let Some(entry) = self.items.iter().find(|i| i.id == id).cloned() else {
            return Ok(None);
        };
        let mut formats = Vec::new();
        if !entry.text.is_empty() {
            formats.push((
                TEXT_OUTPUT_TYPE.to_string(),
                entry.text.clone().into_bytes(),
            ));
        }
        if let Some(data) = self.rich_text_data(id)? {
            let mime = entry
                .rich_text_attachment
                .as_ref()
                .map_or("text/rtf", |a| a.pasteboard_type.as_str());
            formats.push((mime.to_string(), data));
        }
        if let Some(data) = self.image_data(id)? {
            let mime = entry
                .image_attachment
                .as_ref()
                .map_or("image/png", |a| a.pasteboard_type.as_str());
            formats.push((mime.to_string(), data));
        }
        Ok(Some(ClipboardPayload { formats }))
    }

    /// Image bytes of an entry (loaded and validated on demand).
    pub fn image_data(&mut self, id: &str) -> Result<Option<Vec<u8>>, ConfigError> {
        self.attachment_data(id, AttachmentKind::Image)
    }

    /// Rich-text bytes of an entry (loaded and validated on demand).
    pub fn rich_text_data(&mut self, id: &str) -> Result<Option<Vec<u8>>, ConfigError> {
        self.attachment_data(id, AttachmentKind::RichText)
    }

    /// Path of an entry's image file, e.g. for thumbnailing.
    pub fn image_path(&self, id: &str) -> Option<PathBuf> {
        let attachment = self
            .items
            .iter()
            .find(|i| i.id == id)?
            .image_attachment
            .as_ref()?;
        is_safe_attachment_name(&attachment.file_name)
            .then(|| self.paths.attachments_dir.join(&attachment.file_name))
    }

    fn attachment_data(
        &mut self,
        id: &str,
        kind: AttachmentKind,
    ) -> Result<Option<Vec<u8>>, ConfigError> {
        let Some(entry) = self.items.iter().find(|i| i.id == id) else {
            return Ok(None);
        };
        let attachment = match kind {
            AttachmentKind::Image => entry.image_attachment.clone(),
            AttachmentKind::RichText => entry.rich_text_attachment.clone(),
        };
        let Some(attachment) = attachment else {
            return Ok(None);
        };
        let data = (attachment.kind == kind && is_safe_attachment_name(&attachment.file_name))
            .then(|| fs::read(self.paths.attachments_dir.join(&attachment.file_name)).ok())
            .flatten()
            .filter(|d| is_valid_attachment(d, kind));
        if data.is_none() {
            self.discard_attachment(id, kind)?;
        }
        Ok(data)
    }

    fn discard_attachment(&mut self, id: &str, kind: AttachmentKind) -> Result<(), ConfigError> {
        if let Some(index) = self.items.iter().position(|i| i.id == id) {
            match kind {
                AttachmentKind::Image => self.items[index].image_attachment = None,
                AttachmentKind::RichText => self.items[index].rich_text_attachment = None,
            }
            if !self.items[index].has_content() {
                self.items.remove(index);
            }
            self.persist()?;
        }
        Ok(())
    }

    fn save_attachment(
        &self,
        data: &[u8],
        mime: &str,
        kind: AttachmentKind,
    ) -> Option<ClipboardAttachment> {
        if data.is_empty() {
            return None;
        }
        ensure_private_dir(&self.paths.attachments_dir).ok()?;
        let file_name = format!("clipboard-{}.bin", new_id());
        atomic_write(&self.paths.attachments_dir.join(&file_name), data, 0o600).ok()?;
        Some(ClipboardAttachment {
            file_name,
            pasteboard_type: mime.to_string(),
            byte_count: data.len(),
            kind,
        })
    }

    fn referenced_names(&self) -> BTreeSet<String> {
        self.items
            .iter()
            .flat_map(|i| [i.image_attachment.as_ref(), i.rich_text_attachment.as_ref()])
            .flatten()
            .map(|a| a.file_name.clone())
            .collect()
    }

    /// Remove attachment files (and stale temporaries) that no entry references.
    fn cleanup_attachments(&self) {
        let keep = self.referenced_names();
        let Ok(entries) = fs::read_dir(&self.paths.attachments_dir) else {
            return;
        };
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            let stale =
                (name.starts_with("clipboard-") && name.ends_with(".bin") && !keep.contains(&name))
                    || (name.starts_with('.') && name.ends_with(".tmp"));
            if stale {
                let _ = fs::remove_file(entry.path());
            }
        }
    }

    /// Write the history atomically and delete orphaned attachments.
    ///
    /// With a deferred writer ([`ClipboardStore::set_deferred_writer`]) the file is written by a
    /// background thread shortly after the last change (and by [`ClipboardStore::flush`]); the
    /// entries are snapshotted here and serialised there.
    pub fn persist(&self) -> Result<(), ConfigError> {
        if self.unavailable.is_some() {
            return Ok(());
        }
        if let Some(dir) = self.paths.history_file.parent() {
            ensure_private_dir(dir)?;
        }
        match &self.writer {
            Some(writer) => {
                let items = self.items.clone();
                writer.schedule(
                    &self.paths.history_file,
                    0o600,
                    Box::new(move || serde_json::to_vec(&items).map_err(ConfigError::from)),
                );
            }
            None => atomic_write(
                &self.paths.history_file,
                &serde_json::to_vec(&self.items)?,
                0o600,
            )?,
        }
        self.cleanup_attachments();
        Ok(())
    }
}

fn sanitize(entries: &[ClipboardEntry], attachments_dir: &Path) -> Vec<ClipboardEntry> {
    let mut remaining = MAX_ATTACHMENT_STORAGE_BYTES;
    let mut sorted: Vec<&ClipboardEntry> = entries.iter().collect();
    sorted.sort_by(|a, b| {
        b.is_pinned
            .cmp(&a.is_pinned)
            .then_with(|| b.date.total_cmp(&a.date))
    });
    sorted
        .into_iter()
        .filter_map(|entry| {
            if !entry.has_content() || entry.text.len() > TEXT_BYTE_LIMIT {
                return None;
            }
            let image = validated(
                entry.image_attachment.as_ref(),
                AttachmentKind::Image,
                attachments_dir,
                &mut remaining,
            );
            let rich = validated(
                entry.rich_text_attachment.as_ref(),
                AttachmentKind::RichText,
                attachments_dir,
                &mut remaining,
            );
            let result = ClipboardEntry {
                image_attachment: image,
                rich_text_attachment: rich,
                ..entry.clone()
            };
            result.has_content().then_some(result)
        })
        .collect()
}

fn validated(
    attachment: Option<&ClipboardAttachment>,
    kind: AttachmentKind,
    dir: &Path,
    remaining: &mut usize,
) -> Option<ClipboardAttachment> {
    let attachment = attachment?;
    if attachment.kind != kind
        || !is_safe_attachment_name(&attachment.file_name)
        || attachment.byte_count == 0
        || attachment.byte_count > MAX_ATTACHMENT_BYTES_PER_ENTRY
        || attachment.byte_count > *remaining
    {
        return None;
    }
    let path = dir.join(&attachment.file_name);
    let meta = fs::metadata(&path).ok()?;
    if usize::try_from(meta.len()).ok()? != attachment.byte_count {
        return None;
    }
    let data = match fs::read(&path) {
        Ok(d) => d,
        Err(e) if e.kind() == ErrorKind::NotFound => return None,
        Err(_) => return None,
    };
    if !is_valid_attachment(&data, kind) {
        return None;
    }
    *remaining -= attachment.byte_count;
    Some(attachment.clone())
}
