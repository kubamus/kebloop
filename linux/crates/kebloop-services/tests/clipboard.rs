#[test]
fn sensitive_markers_prevent_recording() {
    let mut f = Fixture::new();
    for marker in [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "application/x-nspasteboard-concealed-type",
    ] {
        let mut formats = text("synthetic sensitive text");
        formats.insert(marker.to_string(), Vec::new());
        assert_eq!(
            f.copy(&formats),
            RecordOutcome::Ignored(IgnoreReason::Sensitive),
            "{marker}"
        );
    }
    let mut kde = text("hunter2");
    kde.insert("x-kde-passwordManagerHint".into(), b"secret".to_vec());
    assert_eq!(
        f.copy(&kde),
        RecordOutcome::Ignored(IgnoreReason::Sensitive)
    );
    // A hint with another value is not a secret.
    kde.insert("x-kde-passwordManagerHint".into(), b"clear".to_vec());
    assert!(matches!(f.copy(&kde), RecordOutcome::Recorded(_)));
    assert!(f.store.items().len() == 1);
    f.copy_text("normal text");
    assert_eq!(f.store.items().len(), 2);
}

