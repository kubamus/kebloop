const DAY: u64 = 86_400;
/// 1x1 transparent PNG.
const PNG_HEX: &str = "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c4890000000d4944415478da636460f85f0f0002870180eb47ba920000000049454e44ae426082";

fn png() -> Vec<u8> {
    (0..PNG_HEX.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&PNG_HEX[i..i + 2], 16).unwrap())
        .collect()
}

fn rich_text(byte_count: usize) -> Vec<u8> {
    let prefix = b"{\\rtf1 ";
    let mut data = prefix.to_vec();
    data.extend(std::iter::repeat_n(0x20u8, byte_count - prefix.len() - 1));
    data.push(b'}');
    data
}

fn base() -> SystemTime {
    UNIX_EPOCH + Duration::from_secs(1_800_000_000)
}

fn text(value: &str) -> ClipboardFormats {
    [(
        "text/plain;charset=utf-8".to_string(),
        value.as_bytes().to_vec(),
    )]
    .into()
}

struct Fixture {
    dir: TempDir,
    paths: ClipboardPaths,
    store: ClipboardStore,
    tick: u64,
}

impl Fixture {
    fn new() -> Self {
        Self::with_setup(|_| {})
    }

    fn with_setup(setup: impl FnOnce(&ClipboardPaths)) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let paths = ClipboardPaths::in_dir(&dir.path().join("data"));
        fs::create_dir_all(&paths.attachments_dir).unwrap();
        setup(&paths);
        let store = ClipboardStore::open(paths.clone(), base()).unwrap();
        Self {
            dir,
            paths,
            store,
            tick: 0,
        }
    }

    fn now(&self) -> SystemTime {
        base() + Duration::from_secs(self.tick)
    }

    fn copy(&mut self, formats: &ClipboardFormats) -> RecordOutcome {
        self.tick += 1;
        let now = self.now();
        self.store.record(formats, None, now).unwrap()
    }

    fn copy_text(&mut self, value: &str) -> RecordOutcome {
        self.copy(&text(value))
    }

    fn texts(&self) -> Vec<String> {
        self.store.items().iter().map(|i| i.text.clone()).collect()
    }

    fn reopen(&self) -> ClipboardStore {
        ClipboardStore::open(self.paths.clone(), self.now()).unwrap()
    }

    fn persisted(&self) -> Vec<ClipboardEntry> {
        serde_json::from_slice(&fs::read(&self.paths.history_file).unwrap()).unwrap()
    }

    fn attachment_files(&self) -> usize {
        fs::read_dir(&self.paths.attachments_dir).map_or(0, |d| d.count())
    }
}

fn id_of(outcome: RecordOutcome) -> String {
    match outcome {
        RecordOutcome::Recorded(id) => id,
        other => panic!("expected a recorded entry, got {other:?}"),
    }
}

