#[test]
fn timed_pause_survives_relaunch_and_ignores_offers() {
    let mut f = Fixture::new();
    let now = f.now();
    f.store.pause_for(Duration::from_secs(60), now).unwrap();
    assert_eq!(
        f.store.pause_deadline(),
        Some(now + Duration::from_secs(60))
    );
    assert_eq!(
        f.copy_text("copied during pause"),
        RecordOutcome::Ignored(IgnoreReason::Paused)
    );
    assert!(f.store.items().is_empty());

    let mut relaunched =
        ClipboardStore::open(f.paths.clone(), now + Duration::from_secs(10)).unwrap();
    assert!(relaunched.is_paused(now + Duration::from_secs(10)));
    assert_eq!(
        relaunched
            .record(&text("still paused"), None, now + Duration::from_secs(10))
            .unwrap(),
        RecordOutcome::Ignored(IgnoreReason::Paused)
    );
    relaunched.resume().unwrap();
    assert_eq!(relaunched.pause_deadline(), None);
    assert!(matches!(
        relaunched
            .record(&text("after resume"), None, now + Duration::from_secs(11))
            .unwrap(),
        RecordOutcome::Recorded(_)
    ));
    let saved: serde_json::Value =
        serde_json::from_slice(&fs::read(&f.paths.settings_file).unwrap()).unwrap();
    assert!(saved["pauseUntil"].is_null());
}

#[test]
fn expired_pause_deadline_is_cleared_on_open_and_pauses_are_capped() {
    let mut f = Fixture::new();
    let now = f.now();
    f.store.pause_for(Duration::from_secs(60), now).unwrap();
    let mut relaunched =
        ClipboardStore::open(f.paths.clone(), now + Duration::from_secs(61)).unwrap();
    assert!(!relaunched.is_paused(now + Duration::from_secs(61)));
    assert_eq!(relaunched.pause_deadline(), None);
    assert!(matches!(
        relaunched
            .record(
                &text("recorded after expired pause"),
                None,
                now + Duration::from_secs(62)
            )
            .unwrap(),
        RecordOutcome::Recorded(_)
    ));
    relaunched
        .pause_for(Duration::from_secs(365 * DAY), now)
        .unwrap();
    assert_eq!(
        relaunched.pause_deadline(),
        Some(now + Duration::from_secs(7 * DAY))
    );
    relaunched
        .pause_until(now - Duration::from_secs(1), now)
        .unwrap();
    assert_eq!(relaunched.pause_deadline(), None);
    relaunched
        .pause_until(now + Duration::from_secs(30), now)
        .unwrap();
    assert!(relaunched.is_paused(now));
    relaunched.pause_for(Duration::ZERO, now).unwrap();
    assert!(!relaunched.is_paused(now));
    // A pause that ends is cleared by the periodic tick as well.
    relaunched.pause_for(Duration::from_secs(5), now).unwrap();
    relaunched.tick(now + Duration::from_secs(6)).unwrap();
    assert_eq!(relaunched.pause_deadline(), None);
    assert!(relaunched.is_recording(now + Duration::from_secs(6)));
}

#[test]
fn age_and_count_retention_keep_pins_until_clear() {
    let now = base();
    let pinned = ClipboardEntry {
        is_pinned: true,
        ..ClipboardEntry::new("pinned", "keep this", now - Duration::from_secs(10 * DAY))
    };
    let old = ClipboardEntry::new("old", "expire this", now - Duration::from_secs(10 * DAY));
    let mut f = Fixture::with_setup(|paths| {
        fs::write(
            &paths.history_file,
            serde_json::to_vec(&[pinned, old]).unwrap(),
        )
        .unwrap();
    });
    assert_eq!(f.store.items().len(), 2);
    f.store.set_maximum_age_days(3, now).unwrap();
    f.store.set_maximum_item_count(1, now).unwrap();
    assert_eq!(
        f.store
            .items()
            .iter()
            .map(|i| i.id.as_str())
            .collect::<Vec<_>>(),
        ["pinned"]
    );
    f.copy_text("new item");
    f.copy_text("newer item");
    assert_eq!(f.store.items().len(), 2);
    assert!(f.store.items().iter().any(|i| i.is_pinned));
    assert_eq!(f.store.items().iter().filter(|i| !i.is_pinned).count(), 1);
    let now = f.now();
    assert!(f.store.set_pinned("pinned", false, now).unwrap());
    // Unpinned and older than three days: it expires immediately.
    assert!(f.store.items().iter().all(|i| i.id != "pinned"));
    f.store.set_maximum_age_days(0, now).unwrap();
    f.store.set_maximum_item_count(1, now).unwrap();
    assert_eq!(f.store.items().iter().filter(|i| !i.is_pinned).count(), 1);
    f.store.clear().unwrap();
    assert!(
        f.store.items().is_empty(),
        "Clear History includes pinned items"
    );
    assert!(f.persisted().is_empty());
    assert_eq!(f.reopen().maximum_item_count(), 1);
}

