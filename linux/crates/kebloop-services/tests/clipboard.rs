#[test]
fn deferred_history_writes_are_coalesced_and_flushed() {
    use kebloop_services::persist::DebouncedWriter;
    use std::sync::Arc;
    let mut f = Fixture::new();
    let writer = Arc::new(DebouncedWriter::with_timing(
        Duration::from_secs(60),
        Duration::from_secs(60),
    ));
    f.store.set_deferred_writer(writer.clone());
    for index in 0..30 {
        f.copy_text(&format!("entry {index}"));
    }
    assert!(
        !f.paths.history_file.exists(),
        "the history file is not rewritten per copy"
    );
    assert!(writer.has_pending());
    f.store.flush().unwrap();
    assert_eq!(writer.completed_writes(), 1);
    assert_eq!(f.persisted().len(), 30);
    assert_eq!(f.reopen().items().len(), 30);
    f.store.clear().unwrap();
    f.store.flush().unwrap();
    assert!(f.persisted().is_empty());
}

