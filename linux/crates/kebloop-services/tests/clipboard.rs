#[test]
fn size_limit_uses_utf8_bytes_and_history_is_capped() {
    let mut f = Fixture::new();
    assert!(matches!(
        f.copy_text(&"a".repeat(100 * 1024)),
        RecordOutcome::Recorded(_)
    ));
    assert_eq!(
        f.copy_text(&"a".repeat(100 * 1024 + 1)),
        RecordOutcome::Ignored(IgnoreReason::Empty)
    );
    // A character count alone would incorrectly admit this multibyte string.
    assert_eq!(
        f.copy_text(&"😀".repeat(30_000)),
        RecordOutcome::Ignored(IgnoreReason::Empty)
    );
    assert_eq!(f.store.items().len(), 1);
    assert_eq!(
        f.copy_text("   \n\t "),
        RecordOutcome::Ignored(IgnoreReason::Empty)
    );
    for index in 0..205 {
        f.copy_text(&format!("synthetic entry {index}"));
    }
    assert_eq!(f.store.items().len(), 200);
    assert_eq!(f.store.items()[0].text, "synthetic entry 204");
    assert_eq!(f.store.items()[199].text, "synthetic entry 5");
    let persisted = f.persisted();
    assert_eq!(persisted.len(), 200);
    assert_eq!(persisted[0].text, "synthetic entry 204");
}

