#[test]
fn image_only_and_invalid_attachment_offers() {
    let mut f = Fixture::new();
    let image_only: ClipboardFormats = [("image/png".to_string(), png())].into();
    let id = id_of(f.copy(&image_only));
    assert_eq!(f.store.items()[0].text, "");
    assert_eq!(f.store.items()[0].preview(&Localizer::english()), "Image");
    assert_eq!(f.store.image_data(&id).unwrap(), Some(png()));
    let garbage: ClipboardFormats = [("image/png".to_string(), b"not a png".to_vec())].into();
    assert_eq!(
        f.copy(&garbage),
        RecordOutcome::Ignored(IgnoreReason::Empty)
    );
    // Truncated PNG (no IEND) is rejected.
    let truncated: ClipboardFormats = [("image/png".to_string(), png()[..40].to_vec())].into();
    assert_eq!(
        f.copy(&truncated),
        RecordOutcome::Ignored(IgnoreReason::Empty)
    );
    // A damaged attachment file is dropped when it is read back, removing image-only entries.
    fs::write(f.store.image_path(&id).unwrap(), b"damaged").unwrap();
    assert_eq!(f.store.image_data(&id).unwrap(), None);
    assert!(f.store.items().is_empty());
}

